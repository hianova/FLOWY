uint64_t flowy_hash64(const void *data, size_t len, uint64_t seed) {
    if (!data) return seed;
    const uint8_t *p = (const uint8_t *)data;
    uint64_t h = seed ? seed : 0x9e3779b97f4a7c15ULL;
    for (size_t i = 0; i < len; ++i) {
        h ^= (uint64_t)p[i];
        h *= 0x100000001b3ULL;
    }
    return h;
}

void flowy_json_start(void) { printf("{\n"); }
void flowy_json_end(void) { printf("}\n"); }
void flowy_json_field_str(const char *key, const char *val, bool comma) {
    printf("  \"%s\": \"%s\"%s\n", key, val ? val : "", comma ? "," : "");
}
void flowy_json_field_u64(const char *key, uint64_t val, bool comma) {
    printf("  \"%s\": %" PRIu64 "%s\n", key, val, comma ? "," : "");
}
void flowy_json_field_i64(const char *key, int64_t val, bool comma) {
    printf("  \"%s\": %" PRId64 "%s\n", key, val, comma ? "," : "");
}
void flowy_json_field_bool(const char *key, bool val, bool comma) {
    printf("  \"%s\": %s%s\n", key, val ? "true" : "false", comma ? "," : "");
}
void flowy_json_field_hex64(const char *key, uint64_t val, bool comma) {
    printf("  \"%s\": \"0x%016" PRIx64 "\"%s\n", key, val, comma ? "," : "");
}

int flowy_emit_gpu_shader(const char *path, const char *struct_name,
                          int64_t b_enter, int64_t b_exit, uint32_t qshift, bool is_wgsl) {
    if (!path) return -1;
    FILE *f = fopen(path, "w");
    if (!f) return -1;
    const char *sname = (struct_name && struct_name[0]) ? struct_name : "FlowState64";
    if (is_wgsl) {
        fprintf(f, "// Generated by FLOWY (--emit-wgsl) — 64-Byte Univalent WebGPU Uniform Buffer\n"
                   "const FLOW_QSHIFT : u32 = %uu;\n"
                   "const FLOW_B_ENTER : i32 = %d;\n"
                   "const FLOW_B_EXIT  : i32 = %d;\n\n"
                   "struct %s {\n"
                   "    slot0 : vec4<u32>,\n"
                   "    slot1 : vec4<u32>,\n"
                   "    slot2 : vec4<u32>,\n"
                   "    slot3 : vec4<u32>,\n"
                   "};\n\n"
                   "@group(0) @binding(0) var<uniform> u_flow_state : %s;\n",
                qshift, (int)b_enter, (int)b_exit, sname, sname);
    } else {
        fprintf(f, "// Generated by FLOWY (--emit-metal) — 64-Byte Cache-Line Univalent Metal Buffer\n"
                   "#ifdef __METAL_VERSION__\n"
                   "#include <metal_stdlib>\nusing namespace metal;\n"
                   "#else\n"
                   "#include <stdint.h>\ntypedef uint32_t uint;\ntypedef struct { uint32_t x, y, z, w; } uint4;\n"
                   "#define constant static const\n"
                   "#endif\n\n"
                   "constant uint FLOW_QSHIFT  = %uu;\n"
                   "constant int  FLOW_B_ENTER = %d;\n"
                   "constant int  FLOW_B_EXIT  = %d;\n\n"
                   "struct alignas(64) %s {\n"
                   "    uint4 slot0;\n"
                   "    uint4 slot1;\n"
                   "    uint4 slot2;\n"
                   "    uint4 slot3;\n"
                   "};\n"
                   "static_assert(sizeof(%s) == 64, \"%s must be 64-byte cache-line univalent\");\n",
                qshift, (int)b_enter, (int)b_exit, sname, sname, sname);
    }
    fclose(f);
    return 0;
}

int flowy_emit_ffi_view(const char *path, const char *struct_name,
                        int64_t b_enter, int64_t b_exit, uint32_t qshift) {
    if (!path || !path[0]) return -1;
    const char *ext = strrchr(path, '.');
    if (!ext || (strcmp(ext, ".py") != 0 && strcmp(ext, ".ts") != 0 && strcmp(ext, ".swift") != 0)) {
        fprintf(stderr, "Error: --emit-ffi requires .py, .ts, or .swift extension (got: %s)\n", path);
        return -1;
    }
    FILE *f = fopen(path, "w");
    if (!f) return -1;
    const char *sname = (struct_name && struct_name[0] && strcmp(struct_name, "anonymous") != 0)
                        ? struct_name : "FlowState64";
    if (strcmp(ext, ".py") == 0) {
        fprintf(f, "# Generated by FLOWY (--emit-ffi) — 64-Byte Univalent Zero-Copy ctypes View\n"
                   "import ctypes\n\n"
                   "FLOW_QSHIFT = %u\n"
                   "FLOW_B_ENTER = %" PRId64 "\n"
                   "FLOW_B_EXIT = %" PRId64 "\n\n"
                   "class %s(ctypes.Structure):\n"
                   "    _pack_ = 8\n"
                   "    _fields_ = [\n"
                   "        (\"slot_0\", ctypes.c_uint64),\n"
                   "        (\"slot_1\", ctypes.c_uint64),\n"
                   "        (\"slot_2\", ctypes.c_uint64),\n"
                   "        (\"slot_3\", ctypes.c_uint64),\n"
                   "        (\"slot_4\", ctypes.c_uint64),\n"
                   "        (\"slot_5\", ctypes.c_uint64),\n"
                   "        (\"slot_6\", ctypes.c_uint64),\n"
                   "        (\"slot_7\", ctypes.c_uint64),\n"
                   "    ]\n\n"
                   "assert ctypes.sizeof(%s) == 64, \"%s must be 64-byte cache-line univalent\"\n",
                qshift, b_enter, b_exit, sname, sname, sname);
    } else if (strcmp(ext, ".ts") == 0) {
        fprintf(f, "// Generated by FLOWY (--emit-ffi) — 64-Byte Univalent Zero-Copy DataView\n"
                   "export const FLOW_QSHIFT: number = %u;\n"
                   "export const FLOW_B_ENTER: number = %" PRId64 ";\n"
                   "export const FLOW_B_EXIT: number = %" PRId64 ";\n\n"
                   "export class %sView {\n"
                   "    public static readonly BYTE_LENGTH = 64;\n"
                   "    private readonly view: DataView;\n\n"
                   "    constructor(buffer: ArrayBufferLike, byteOffset: number = 0) {\n"
                   "        if (buffer.byteLength - byteOffset < %sView.BYTE_LENGTH) {\n"
                   "            throw new RangeError(\"Buffer too small for 64-byte univalent %sView\");\n"
                   "        }\n"
                   "        this.view = new DataView(buffer, byteOffset, %sView.BYTE_LENGTH);\n"
                   "    }\n\n"
                   "    getSlotU64(index: number): bigint {\n"
                   "        if (index < 0 || index >= 8) throw new RangeError(\"Slot index out of [0, 7]\");\n"
                   "        return this.view.getBigUint64(index * 8, true);\n"
                   "    }\n\n"
                   "    setSlotU64(index: number, val: bigint): void {\n"
                   "        if (index < 0 || index >= 8) throw new RangeError(\"Slot index out of [0, 7]\");\n"
                   "        this.view.setBigUint64(index * 8, val, true);\n"
                   "    }\n"
                   "}\n",
                qshift, b_enter, b_exit, sname, sname, sname, sname);
    } else {
        fprintf(f, "// Generated by FLOWY (--emit-ffi) — 64-Byte Univalent Swift Frozen Struct\n"
                   "import Foundation\n\n"
                   "public let FLOW_QSHIFT: UInt32 = %u\n"
                   "public let FLOW_B_ENTER: Int64 = %" PRId64 "\n"
                   "public let FLOW_B_EXIT: Int64 = %" PRId64 "\n\n"
                   "@frozen\n"
                   "public struct %s {\n"
                   "    public var slot0: UInt64 = 0\n"
                   "    public var slot1: UInt64 = 0\n"
                   "    public var slot2: UInt64 = 0\n"
                   "    public var slot3: UInt64 = 0\n"
                   "    public var slot4: UInt64 = 0\n"
                   "    public var slot5: UInt64 = 0\n"
                   "    public var slot6: UInt64 = 0\n"
                   "    public var slot7: UInt64 = 0\n"
                   "    public init(slot0: UInt64 = 0, slot1: UInt64 = 0, slot2: UInt64 = 0, slot3: UInt64 = 0,\n"
                   "                slot4: UInt64 = 0, slot5: UInt64 = 0, slot6: UInt64 = 0, slot7: UInt64 = 0) {\n"
                   "        self.slot0 = slot0; self.slot1 = slot1; self.slot2 = slot2; self.slot3 = slot3\n"
                   "        self.slot4 = slot4; self.slot5 = slot5; self.slot6 = slot6; self.slot7 = slot7\n"
                   "    }\n"
                   "}\n\n"
                   "@inlinable\n"
                   "public func flowVerify%sUnivalent64() -> Bool {\n"
                   "    return MemoryLayout<%s>.size == 64 && MemoryLayout<%s>.stride == 64\n"
                   "}\n",
                qshift, b_enter, b_exit, sname, sname, sname, sname);
    }
    fclose(f);
    return 0;
}

static int ensure_dir_exists(const char *path) {
    char tmp[512];
    size_t len = strlen(path);
    if (len == 0 || len >= sizeof(tmp)) return -1;
    memcpy(tmp, path, len + 1);
    for (size_t i = 1; i < len; ++i) {
        if (tmp[i] == '/') {
            tmp[i] = '\0';
            if (mkdir(tmp, 0755) != 0) {
                struct stat st;
                if (errno != EEXIST || stat(tmp, &st) != 0 || !S_ISDIR(st.st_mode)) return -1;
            }
            tmp[i] = '/';
        }
    }
    if (mkdir(tmp, 0755) != 0) {
        struct stat st;
        if (errno != EEXIST || stat(tmp, &st) != 0 || !S_ISDIR(st.st_mode)) return -1;
    }
    return 0;
}

int cmd_init_run(int argc, char **argv, bool json_mode) {
    const char *raw_dir = NULL;
    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "-h") == 0 || strcmp(argv[i], "--help") == 0) {
            printf("FLOWY init — One-Command Lean 4 + C11 64B Univalent + FLOW ASM Project Scaffolder\n\n"
                   "USAGE:\n    flowy init <target_dir> [--json]\n\n"
                   "OPTIONS:\n"
                   "    --json       Deterministic JSON output\n"
                   "    -h, --help   Print help information\n");
            return 0;
        } else if (argv[i][0] != '-') {
            raw_dir = argv[i];
        }
    }
    if (!raw_dir || !raw_dir[0] || strlen(raw_dir) > 380) {
        fprintf(stderr, "Error: flowy init requires a valid <target_dir> path.\n");
        return 1;
    }
    char target_dir[384];
    snprintf(target_dir, sizeof(target_dir), "%s", raw_dir);
    size_t tlen = strlen(target_dir);
    while (tlen > 1 && target_dir[tlen - 1] == '/') {
        target_dir[--tlen] = '\0';
    }

    char d_lean[512], d_inc[512], d_src[512];
    char f_lean[512], f_hdr[512], f_src[512], f_mk[512];
    snprintf(d_lean, sizeof(d_lean), "%s/lean", target_dir);
    snprintf(d_inc,  sizeof(d_inc),  "%s/include", target_dir);
    snprintf(d_src,  sizeof(d_src),  "%s/src", target_dir);

    if (ensure_dir_exists(target_dir) != 0 ||
        ensure_dir_exists(d_lean) != 0 ||
        ensure_dir_exists(d_inc) != 0 ||
        ensure_dir_exists(d_src) != 0) {
        fprintf(stderr, "Error: failed to create project directories in %s\n", target_dir);
        return 1;
    }

    snprintf(f_lean, sizeof(f_lean), "%s/lean/Spec.lean", target_dir);
    snprintf(f_hdr,  sizeof(f_hdr),  "%s/include/project_state.h", target_dir);
    snprintf(f_src,  sizeof(f_src),  "%s/src/main.c", target_dir);
    snprintf(f_mk,   sizeof(f_mk),   "%s/Makefile", target_dir);

    FILE *fp = fopen(f_lean, "w");
    if (!fp) return 1;
    fprintf(fp, "import Init.Data.BitVec\nopen BitVec\n\n"
                "structure ProjectState64 where\n"
                "  reserveA      : Nat\n  reserveB      : Nat\n  vaultBalance  : Nat\n  feePool       : Nat\n"
                "  epochTick     : Nat\n  activeMask    : Nat\n  sieveFlags    : Nat\n  thermalKelvin : Nat\n\n"
                "def route_op_mask : UInt32 := 0x0000000D\n"
                "def b_enter_q16   : Int    := 73728\n"
                "def b_exit_q16    : Int    := 57344\n"
                "def req_mask      : UInt64 := 0x000000000000000F\n"
                "def req_values    : UInt64 := 0x0000000000000005\n"
                "def weight_q16    : Int32  := 3276\n"
                "def qshift        : UInt32 := 16\n"
                "def dietz_midpoint (a b : BitVec 64) : BitVec 64 := (a &&& b) + ((a ^^^ b) >>> 1)\n\n"
                "theorem deadband_ordered : b_exit_q16 < b_enter_q16 := by decide\n"
                "theorem route_well_formed : route_op_mask > 0 ∧ qshift = 16 ∧ weight_q16 > 0 ∧ (req_values &&& req_mask) = req_values := by decide\n"
                "theorem midpoint_idempotent (x : BitVec 64) : dietz_midpoint x x = x := by simp [dietz_midpoint]\n"
                "theorem step_conserved (s0 delta : Nat) (h : delta <= s0) : (s0 - delta) + delta = s0 := by omega\n");
    fclose(fp);

    fp = fopen(f_hdr, "w");
    if (!fp) return 1;
    fprintf(fp, "/* Generated by flowy init — 64-Byte Cache-Line Univalent State & FLOW ASM Substrate */\n"
                "#ifndef PROJECT_STATE_H\n#define PROJECT_STATE_H\n\n#include <stdint.h>\n\n"
                "typedef struct {\n"
                "    _Alignas(64) uint64_t reserveA;\n"
                "    uint64_t reserveB;\n"
                "    uint64_t vaultBalance;\n"
                "    uint64_t feePool;\n"
                "    uint64_t epochTick;\n"
                "    uint64_t activeMask;\n"
                "    uint64_t sieveFlags;\n"
                "    uint64_t thermalKelvin;\n"
                "} ProjectState64;\n\n"
                "#if defined(__STDC_VERSION__) && (__STDC_VERSION__ >= 201112L)\n"
                "_Static_assert(sizeof(ProjectState64) == 64, \"ProjectState64 must be 64 bytes\");\n"
                "_Static_assert(_Alignof(ProjectState64) == 64, \"ProjectState64 must be 64-byte aligned\");\n"
                "#endif\n\n"
                "static inline uint64_t project_dietz_midpoint_u64(uint64_t a, uint64_t b) {\n"
                "    return (a & b) + ((a ^ b) >> 1U);\n"
                "}\n\n"
                "static inline uint64_t project_asm_qadd_u64(uint64_t a, uint64_t b, uint64_t *sieve_inout) {\n"
                "    uint64_t sum = a + b;\n"
                "    if (sum < a) {\n"
                "        if (sieve_inout) *sieve_inout &= ~0x2ULL;\n"
                "        return UINT64_MAX;\n"
                "    }\n"
                "    return sum;\n"
                "}\n\n"
                "static inline int project_verify_conservation(const ProjectState64 *a, const ProjectState64 *b) {\n"
                "    return (a && b) ? ((a->reserveA + a->reserveB) == (b->reserveA + b->reserveB)) : 0;\n"
                "}\n\n#endif /* PROJECT_STATE_H */\n");
    fclose(fp);

    fp = fopen(f_src, "w");
    if (!fp) return 1;
    fprintf(fp, "#include <stdio.h>\n#include <assert.h>\n#include \"../include/project_state.h\"\n\n"
                "int main(void) {\n"
                "    uint64_t sieve = 0x3FFULL;\n"
                "    ProjectState64 s0 = { .reserveA = 1000, .reserveB = 500, .sieveFlags = sieve, .thermalKelvin = 300 };\n"
                "    ProjectState64 s1 = { .reserveA = 900,  .reserveB = 600, .sieveFlags = sieve, .thermalKelvin = 300 };\n"
                "    assert(project_verify_conservation(&s0, &s1) == 1);\n"
                "    assert(project_dietz_midpoint_u64(UINT64_MAX, UINT64_MAX) == UINT64_MAX);\n"
                "    assert(project_asm_qadd_u64(UINT64_MAX, 1ULL, &sieve) == UINT64_MAX && (sieve & 0x2ULL) == 0);\n"
                "    printf(\"[PASS] ProjectState64 (64B Univalent + FLOW ASM) conservation & boundary healing verified.\\n\");\n"
                "    return 0;\n"
                "}\n");
    fclose(fp);

    fp = fopen(f_mk, "w");
    if (!fp) return 1;
    fprintf(fp, "CC ?= cc\nCFLAGS ?= -std=c11 -Wall -Wextra -Werror -pedantic -O2\n"
                "LEAN ?= $(shell command -v lean 2>/dev/null || echo $$HOME/.elan/bin/lean)\n\n"
                ".PHONY: all test verify-lean clean\n\n"
                "all: build/app\n\n"
                "build/app: src/main.c include/project_state.h\n"
                "\t@mkdir -p build\n"
                "\t$(CC) $(CFLAGS) -I./include src/main.c -o build/app\n\n"
                "test: build/app\n"
                "\t./build/app\n\n"
                "verify-lean:\n"
                "\t$(LEAN) lean/Spec.lean\n\n"
                "clean:\n"
                "\trm -rf build\n");
    fclose(fp);

    if (json_mode) {
        flowy_json_start();
        flowy_json_field_str("subcommand", "init", true);
        flowy_json_field_str("target_dir", target_dir, true);
        flowy_json_field_str("lean_spec", f_lean, true);
        flowy_json_field_str("header_file", f_hdr, true);
        flowy_json_field_str("source_file", f_src, true);
        flowy_json_field_str("makefile", f_mk, true);
        flowy_json_field_bool("scaffold_complete", true, false);
        flowy_json_end();
    } else {
        printf("=== FLOWY Project Scaffolder ===\n"
               "Target Directory : %s\n"
               "  - Lean SSOT    : %s\n"
               "  - 64B Header   : %s\n"
               "  - Entry Source : %s\n"
               "  - Build System : %s\n"
               "Status           : READY (Run `make -C %s test`)\n",
               target_dir, f_lean, f_hdr, f_src, f_mk, target_dir);
    }
    return 0;
}

